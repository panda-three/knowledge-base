/*----------------------------------------------------------------------
【程序改错】
------------------------------------------------------------------------
题目：程序从一维整型数组a中找出符合条件的元素存入一维数组b中，该元素其后连
      续的三个元素呈谷形或峰形(即呈凸形或凹形)。再将b数组的元素按程序运行
      结果所示填入二维数组c的右上角。（已知b数组中元素个数大于等于M）

例如：有连续6个元素：23,31,14,18,16,5，23后连续3个元素是31,14,18，呈大小
      大谷形；31后连续3个元素14,18,16，呈小大小峰形，因此23和31都满足条件，
      需存入数组b。而14后连续3个元素18,16,5，不满足条件，14不存入数组b。

程序运行结果如下：
23 31 18  16  27

16 18  31  23
   16  18  31
       16  18
           16
-----------------------------------------------------------------------
注意：不得增行或删行，不得更改程序的结构
----------------------------------------------------------------------*/
#include <stdio.h>

#define N 10
#define M 4

int find(int b[], int a[])
{
    int i,k;
    int cont1,cont2;
/***********FOUND***********/
    for(i=0;i<N;i++)
    {
        cont1=(a[i+1]>a[i+2] && a[i+2]<a[i+3]);
        cont2=(a[i+1]<a[i+2] && a[i+2]>a[i+3]);
        if (cont1 || cont2)
            b[k++]=a[i];
    }
    return k;
}
/***********FOUND***********/
void fill(int b[],int c[][])
{
    int j,k,p;
    for(k=0;k<M;k++)
    {
/***********FOUND***********/
        j=k-1;
        for(p=0;p<=k;p++)
            c[p][j++]=b[k];
    }
}
int main(void)
{
    int a[N]={23,31,14,18,16,5,27,9,4,6};
    int b[N-3],c[M][M],i,j;
    int len=find(b,a);
    for (i=0;i<len;i++)
        printf("%d ",b[i]);
    printf("\n");
    printf("\n");
    fill(c,b);
    for (i=0;i<M;i++)
    {
        for(j=0;j<i;j++)
            printf("   ");
        for(j=i;j<M;++j)
            printf("%3d",c[i][j]);
        printf("\n");
    }
    return 0;
}