#include <stdio.h>

void FindChar(char strBuf[]) 
{
    int nArr[128][2]= {0};
    int i,j,k;
    char ch;
    for (i = 0; ch=strBuf[i]; i++)
    {
        nArr[ch][0]++;
        if (!nArr[ch][1]) 
        {
/***********FOUND***********/
            nArr[i][1] = 1;
        }
    }
    j=0;
    for (i=32; i<128; i++) 
    {
        if (nArr[i][0]== 1) 
        {
            nArr[j][0]=i;
            nArr[j][1]=nArr[i][1];
            j++;
        }
    }
    if(!j) 
    {
        printf("输入的字符串中没有出现单个字母.\n");
        return;
    }
/***********FOUND***********/
    k = nArr[0][0];  
    for(i=1; i<j; i++) 
    {
        if (nArr[i][1]<k) 
        {
/***********FOUND***********/
            k = i;
        }
    }
    printf("在\"%s\"中出现一次的首个英文字母是: ",strBuf);
    printf("%c\n",strBuf[k-1]);    
}

int main(void) 
{
    char str[200]="azabccdeff";    
    FindChar(str);
    return 0;
}
