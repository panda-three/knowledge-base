#include<stdio.h>
#include<string.h>
#include<math.h>
#include<ctype.h>
#include<stdlib.h>

void output(unsigned n)
{
    int i,j;
    char a[30][60]= {""};
    for(i=0; i<n; i++) 
    {
/**************************FOUND**************************/                
        if (i<n/2) 
        {
            for (j=i; j<n-1; j++) 
            {
                a[i][j-i]=' ';
            }
            for (j=0; j<2*i+1; j++)
            {
                a[i][n-i-1+j]='*';
            }
        }
        else
        {
            for (j=0; j<2*n; j++) 
            {
/**************************FOUND**************************/
                a[i][j]=a[n-i][j];
            }
        }
    }
    for(i=0; i<n; i++)
    {
        puts(a[i]);
    }
}

int main() 
{
    unsigned n;
    do {
        printf("请输入一个小于30的正整数：");
        scanf("%d",&n);
/*******************FOUND*******************/
    }while(n%2 && n<30);
    output(n);
    return 0;
}
