#include<stdio.h>
#include<string.h>
#include<math.h>
#include<ctype.h>
#include<stdlib.h>

#define N 4

void binary_power(unsigned int x)
{
    unsigned int s,t,y;
    printf("%u=",x);
    while(x>0)
    {
        y=x;
        s=1;
        t=0;
/***********FOUND***********/
        while(y)
        {
            s*=2;
/***********FOUND***********/
            y+=2;
            ++t;
        }
        printf("2^%u+",t);
/***********FOUND***********/
        x-=t;
    }
    printf("\b \n");
}
int main()
{
    unsigned int n[N]={1,15,32,144};
    int i;
    for(i=0;i<N;++i)
        binary_power(n[i]);
    return 0;
}
